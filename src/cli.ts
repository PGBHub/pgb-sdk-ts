#!/usr/bin/env node

import * as fs from "fs";
import * as path from "path";
import { createClient, type SchemaJson } from "./client";

export async function runCli() {
  const args = process.argv.slice(2);
  const command = args[0] || "pull";

  if (command !== "pull" && command !== "inspect") {
    console.log(`
PGBox CLI — Type generation and schema inspection

Usage:
  npx pgbox pull      Pull /schema.json and generate local TypeScript declaration file (pgbox.d.ts)
  npx pgbox inspect   Print semantic schema JSON to stdout

Options:
  --endpoint <url>    PGBox Cloud endpoint (default: $PGBOX_ENDPOINT or https://cloud.pgboxhub.com)
  --key <api-key>     PGBox API Key (default: $PGBOX_API_KEY)
  --db <dbname>       Target database name (default: postgres)
  --out <filename>    Output filename (default: pgbox.d.ts)
`);
    process.exit(0);
  }

  const endpointIndex = args.indexOf("--endpoint");
  const endpoint = endpointIndex !== -1 ? args[endpointIndex + 1] : process.env.PGBOX_ENDPOINT || "https://cloud.pgboxhub.com";

  const keyIndex = args.indexOf("--key");
  const apiKey = keyIndex !== -1 ? args[keyIndex + 1] : process.env.PGBOX_API_KEY;

  const dbIndex = args.indexOf("--db");
  const database = dbIndex !== -1 ? args[dbIndex + 1] : process.env.PGBOX_DATABASE || "postgres";

  const outIndex = args.indexOf("--out");
  const outputFile = outIndex !== -1 ? args[outIndex + 1] : "pgbox.d.ts";

  console.log(`📡 Connecting to PGBox at ${endpoint} (db: ${database})...`);
  const client = createClient({ endpoint, apiKey, database });

  try {
    const schema = await client.getSchema();

    if (command === "inspect") {
      console.log(JSON.stringify(schema, null, 2));
      return;
    }

    console.log(`✨ Generating TypeScript type definitions from schema (v${schema.version})...`);
    const dtsContent = generateDeclarationContent(schema);

    const outPath = path.resolve(process.cwd(), outputFile);
    fs.writeFileSync(outPath, dtsContent, "utf-8");
    console.log(`✅ Successfully generated typed schema definitions: ${outputFile}`);
    console.log(`💡 You can now import and use full typed autocomplete with @pgbox/client!`);
  } catch (err) {
    console.error(`❌ Error executing pgbox ${command}:`, (err as Error).message);
    process.exit(1);
  }
}

function generateDeclarationContent(schema: SchemaJson): string {
  const tableInterfaces: string[] = [];
  const actionSignatures: string[] = [];

  for (const [_key, table] of Object.entries(schema.tables)) {
    const interfaceName = toPascalCase(table.name);
    const fields = table.columns.map((col) => {
      const opt = col.nullable ? "?" : "";
      return `    /** ${col.name} (${col.data_type}) */\n    ${col.name}${opt}: ${col.type_ts};`;
    });

    tableInterfaces.push(`  export interface ${interfaceName} {\n${fields.join("\n")}\n  }`);
  }

  for (const [actionName, action] of Object.entries(schema.actions)) {
    const desc = action.description ? `/** ${action.description} */\n` : "";
    actionSignatures.push(
      `      ${desc}${actionName}(params?: Record<string, unknown>, opts?: { dryRun?: boolean }): Promise<ActionResponse>;`
    );
  }

  return `// Auto-generated by PGBox CLI (npx pgbox pull)
// Do not edit directly. Re-run 'npx pgbox pull' to sync latest database changes.

import { ActionResponse } from "@pgbox/client";

declare module "@pgbox/client" {
  export namespace Schema {
${tableInterfaces.join("\n\n")}
  }

  export interface PGBoxClient {
    readonly actions: {
${actionSignatures.length > 0 ? actionSignatures.join("\n") : "      [key: string]: (params?: Record<string, unknown>, opts?: { dryRun?: boolean }) => Promise<ActionResponse>;"}
    };
  }
}
`;
}

function toPascalCase(str: string): string {
  return str
    .replace(/(?:^\w|[A-Z]|\b\w)/g, (letter) => letter.toUpperCase())
    .replace(/[\s\-_]+/g, "");
}

if (require.main === module) {
  runCli();
}
